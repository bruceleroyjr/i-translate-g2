import { WindowState, setTiming, windowMsFor, msgKindFor, timing } from '../src/window.ts';
let fails = 0;
const check = (name, ok) => { console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}`); if (!ok) fails++; };
const t = 1000;
setTiming({ messageS: 15, screenOffS: 10, kinds: { translations: 10 } });
check('kinds map', msgKindFor({ kind: 'translation' }) === 'translations' && msgKindFor({ kind: 'status' }) === null);
check('own time / default', windowMsFor({ kind: 'translation' }) === 10000 && windowMsFor({ kind: 'status' }) === 15000);
const pop = (kind) => { const w = new WindowState(); w.offer({ seq: 1, kind, title: 'T', text: 'x', original: 'y', pushed: true }, t); return w; };
let w = pop('translation');
check('translation card: countdown starts at 10 s', w.view(t).secondsLeft === 10);
check('translation dueIn = 10 s', w.dueIn(t) === 10000);
w.tick(t + 9900); check('still up at 9.9 s', !!w.item);
w.tick(t + 10000); check('closes at 10 s', !w.item);
w = pop('status');
w.tick(t + 14900); check('status uses the 15 s default', !!w.item);
w.tick(t + 15000); check('status closes at 15 s', !w.item);
w = pop('wake');
w.tick(t + 60000); check('the Listening card has no timer', !!w.item && w.dueIn(t) === null);
setTiming({ messageS: 15, screenOffS: 10 });
check('no kinds given: all default', windowMsFor({ kind: 'translation' }) === 15000);
check('screen off after 10 s', timing.idleSleepMs === 10000);
setTiming({ messageS: 15, screenOffS: 0 });
check('screen off "Never" = no idle sleep', !Number.isFinite(timing.idleSleepMs));
console.log(fails ? `${fails} FAILED` : 'ALL PASS');
process.exit(fails ? 1 : 0);
