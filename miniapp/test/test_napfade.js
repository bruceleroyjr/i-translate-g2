import { asleepFrame, IDLE_FADE_MS, NAPFADE_FRAMES, PAUSED_FADE_MS, WINDOW_MS, IdleSleep, IDLE_SLEEP_MS } from '../src/window.ts';
import { existsSync } from 'node:fs';

let fails = 0;
const check = (name, ok, detail = '') => {
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${ok ? '' : `  ${detail}`}`);
  if (!ok) fails++;
};
check('fade starts 10 s after she falls asleep', IDLE_FADE_MS === 10_000);
check('asleep < 10 s: the nap loop', ['nap1', 'nap2'].includes(asleepFrame(0)) && ['nap1', 'nap2'].includes(asleepFrame(9_999)));
const seq = [10_000, 11_000, 12_000, 13_000, 60_000, 3_600_000].map(asleepFrame);
check('then napfade1, 2, 3, blank one a second - and blank for good', seq.join() === 'napfade1,napfade2,napfade3,blank,blank,blank', seq.join());
check('frames exist in public/avatar48', NAPFADE_FRAMES.filter((f) => f !== 'blank').every((f) => existsSync(`public/avatar48/${f}.png`)));
const s = new IdleSleep();
const T0 = 1_700_000_000_000; 
s.update(T0, true);
const t = T0 + IDLE_SLEEP_MS + IDLE_FADE_MS + 5_000;
check('fully faded after sleep + fade + 5 s of quiet', s.update(t, true) && asleepFrame(t - s.asleepAt) === 'blank');
s.activity(t);
check('gesture: awake again (no fade frame)', s.update(t + 100, true) === false);
check('anything going on: awake', s.update(t + 20_000, false) === false);

{
  const { setTiming, timing, WindowState, ScreenSleep } = await import('../src/window.ts');
  const { load } = await import('../src/settings.ts');
  const T = 1_700_000_000_000;
  setTiming({ screenOffS: 30, messageS: 5 });
  const z = new IdleSleep();
  z.update(T, true);
  check('display off after 30 s: awake at 29 s, asleep/off at 30 s', !z.update(T + 29_000, true) && z.update(T + 30_000, true));
  check('fade starts at once when she falls asleep', asleepFrame(0) === 'napfade1');
  check('blank once the fade has played', asleepFrame(3_000) === 'blank');
  const p = new ScreenSleep();
  p.update(T, { listening: false, needsScreen: false });
  check('paused: no fade at 29 s', p.update(T + 29_000, { listening: false, needsScreen: false }) === null);
  check('paused: fade at 30 s', p.update(T + 30_000, { listening: false, needsScreen: false }) === 'fade');
  check('paused: dark once the fade has played', p.update(T + 34_000, { listening: false, needsScreen: false }) === 'sleep');
  const w = new WindowState();
  w.offer({ seq: 1, kind: 'reply', title: 'Q', text: 'hi' }, T);
  check('message 5 s: countdown starts at 5s', w.view(T).secondsLeft === 5);
  check('message 5 s: still open at 4.9 s', !w.tick(T + 4_900).some((f) => f.type === 'clear'));
  check('message 5 s: closes at 5 s', w.tick(T + 5_000).some((f) => f.type === 'clear') && !w.item);
  setTiming({ screenOffS: 0, messageS: 15 });
  const n = new IdleSleep();
  n.update(T, true);
  check('Never: still awake after a day', !n.update(T + 86_400_000, true));
  const q = new ScreenSleep();
  q.update(T, { listening: false, needsScreen: false });
  check('Never: paused screen stays on after a day', q.update(T + 86_400_000, { listening: false, needsScreen: false }) === null && !q.off);
  setTiming({});
  check('setTiming({}) = the defaults', timing.windowMs === WINDOW_MS && timing.idleSleepMs === IDLE_SLEEP_MS && timing.idleFadeMs === 0 && timing.pausedFadeMs === PAUSED_FADE_MS);
  const mem = (v) => ({ get: async () => v, set: async () => undefined });
  const fresh = await load(mem(''));
  check('settings default: display off after 10 s, message 15 s', fresh.screenOffS === 10 && fresh.messageS === 15);
  const old = await load(mem(JSON.stringify({ relayUrl: 'x' })));
  check('settings saved before Timeouts existed get the defaults', old.screenOffS === 10 && old.messageS === 15);
  const bad = await load(mem(JSON.stringify({ screenOffS: 'x', messageS: 999 })));
  check('odd saved values fall back to the defaults', bad.screenOffS === 10 && bad.messageS === 15);
  const never = await load(mem(JSON.stringify({ screenOffS: 0, messageS: 60 })));
  check('Never (0) and 1 minute are kept', never.screenOffS === 0 && never.messageS === 60);
}
console.log(fails ? `${fails} FAILED` : 'all passed');
process.exit(fails ? 1 : 0);
